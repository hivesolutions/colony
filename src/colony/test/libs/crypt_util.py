import colony


class CryptTest(colony.ColonyTestCase):
    """
    Class that tests the various functions related
    with the cryptography utilities in Colony.
    """

    def test_password_crypt(self):
        """
        Tests the password crypt function, making sure that the
        legacy hash methods are kept and that the PBKDF2 SHA256
        one generates hashes in the PHC string format.
        """

        result = colony.password_crypt("password", "omni", "sha256")
        self.assertEqual(
            result,
            "{sha256}ac377675ce11c468ca480121b0b94242c89c8cfa598a68b98c80f1fc43d893eb",
        )

        result = colony.password_crypt("password", "omni", "plain")
        self.assertEqual(result, "{plain}passwordomni")

        result = colony.password_crypt("password", hash_method="pbkdf2_sha256")
        self.assertEqual(type(result), str)
        self.assertEqual(result.startswith("$pbkdf2-sha256$600000$"), True)
        self.assertEqual(len(result.split("$")), 5)
        self.assertEqual(len(result.split("$")[3]), 22)
        self.assertEqual(len(result.split("$")[4]), 43)

        first = colony.password_crypt(
            "password", hash_method="pbkdf2_sha256", iterations=1000
        )
        second = colony.password_crypt(
            "password", hash_method="pbkdf2_sha256", iterations=1000
        )
        self.assertEqual(first.startswith("$pbkdf2-sha256$1000$"), True)
        self.assertNotEqual(first, second)
        self.assertNotEqual(first.split("$")[3], second.split("$")[3])

        result = colony.password_crypt(
            "password", "omni", "PBKDF2_SHA256", iterations=1000
        )
        self.assertEqual(result.startswith("$pbkdf2-sha256$1000$"), True)
        self.assertEqual(colony.password_match(result, "password"), True)
        self.assertEqual(colony.password_match(result, "password", "omni"), True)
        self.assertEqual(colony.password_match(result, "passwordomni"), False)

    def test_password_crypt_unicode(self):
        """
        Tests the password crypt function using unicode passwords,
        that should be encoded as UTF-8 before being hashed.
        """

        result = colony.password_crypt(
            colony.legacy.u("密码"), hash_method="pbkdf2_sha256", iterations=1000
        )
        self.assertEqual(type(result), str)
        self.assertEqual(colony.password_match(result, colony.legacy.u("密码")), True)
        self.assertEqual(colony.password_match(result, colony.legacy.u("密")), False)

    def test_password_match(self):
        """
        Tests the password match function for both the legacy
        hashes and the PBKDF2 SHA256 ones, including the hashes
        generated by passlib (compatibility).
        """

        password_hash = colony.password_crypt("password", "omni", "sha256")
        self.assertEqual(colony.password_match(password_hash, "password", "omni"), True)
        self.assertEqual(colony.password_match(password_hash, "password"), False)
        self.assertEqual(colony.password_match(password_hash, "wrong", "omni"), False)

        password_hash = colony.password_crypt("password", "omni", "plain")
        self.assertEqual(colony.password_match(password_hash, "password", "omni"), True)
        self.assertEqual(colony.password_match(password_hash, "password"), False)

        password_hash = "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$hRRjgXWkW8ResfIvBP99J/T4vkgEmMRV/0tJTOjR59I"
        self.assertEqual(colony.password_match(password_hash, "password"), True)
        self.assertEqual(colony.password_match(password_hash, "password", "omni"), True)
        self.assertEqual(colony.password_match(password_hash, "Password"), False)
        self.assertEqual(colony.password_match(password_hash, ""), False)

        password_hash = "$pbkdf2-sha256$01000$MDEyMzQ1Njc4OWFiY2RlZg$hRRjgXWkW8ResfIvBP99J/T4vkgEmMRV/0tJTOjR59I"
        self.assertEqual(colony.password_match(password_hash, "password"), True)

        password_hash = "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$FN/YRwbrqMjGd663C.f2ni5YBVGooq4Wv5xZfOeBEmg"
        self.assertEqual(
            colony.password_match(password_hash, colony.legacy.u("密码")), True
        )
        self.assertEqual(colony.password_match(password_hash, "password"), False)

        self.assertEqual(colony.password_match("password", "password"), False)
        self.assertEqual(colony.password_match("", ""), False)
        self.assertEqual(colony.password_match("$pbkdf2-sha256$", "password"), False)
        self.assertEqual(
            colony.password_match(
                "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$", "password"
            ),
            False,
        )
        self.assertEqual(
            colony.password_match(
                "$pbkdf2-sha256$0$MDEyMzQ1Njc4OWFiY2RlZg$hRRjgXWkW8ResfIvBP99J/T4vkgEmMRV/0tJTOjR59I",
                "password",
            ),
            False,
        )
        self.assertEqual(
            colony.password_match(
                "$pbkdf2-sha256$1000$A$hRRjgXWkW8ResfIvBP99J/T4vkgEmMRV/0tJTOjR59I",
                "password",
            ),
            False,
        )
        self.assertEqual(
            colony.password_match(
                "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$A", "password"
            ),
            False,
        )
        self.assertEqual(
            colony.password_match(
                "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$hRRjgXWkW8ResfIvBP99J+T4vkgEmMRV/0tJTOjR59I",
                "password",
            ),
            False,
        )

    def test_password_outdated(self):
        """
        Tests the password outdated function, making sure that only
        the PBKDF2 SHA256 hash method is an upgrade target and that
        the hashes with less iterations are considered outdated.
        """

        legacy_hash = colony.password_crypt("password", "omni", "sha256")
        pbkdf2_hash = colony.password_crypt("password", hash_method="pbkdf2_sha256")
        weak_hash = "$pbkdf2-sha256$1000$MDEyMzQ1Njc4OWFiY2RlZg$hRRjgXWkW8ResfIvBP99J/T4vkgEmMRV/0tJTOjR59I"

        self.assertEqual(colony.password_outdated(legacy_hash), True)
        self.assertEqual(colony.password_outdated(legacy_hash, "pbkdf2_sha256"), True)
        self.assertEqual(colony.password_outdated(legacy_hash, "PBKDF2_SHA256"), True)
        self.assertEqual(colony.password_outdated(pbkdf2_hash), False)
        self.assertEqual(colony.password_outdated(weak_hash), True)
        self.assertEqual(colony.password_outdated(weak_hash, iterations=1000), False)
        self.assertEqual(colony.password_outdated(weak_hash, iterations=1001), True)
        self.assertEqual(
            colony.password_outdated("$pbkdf2-sha256$", "pbkdf2_sha256"), True
        )

        self.assertEqual(colony.password_outdated(legacy_hash, "sha256"), False)
        self.assertEqual(colony.password_outdated(pbkdf2_hash, "sha256"), False)
        self.assertEqual(colony.password_outdated(weak_hash, "md5"), False)

    def test_md5_crypt(self):
        """
        Tests the MD5 crypt function using some simple values.
        """

        result = colony.md5_crypt("password", "salt")
        self.assertEqual(type(result), str)
        self.assertEqual(result, "$1$salt$qJH7.N4xYta3aEG/dfqo/0")

        result = colony.md5_crypt("password", "01234567")
        self.assertEqual(type(result), str)
        self.assertEqual(result, "$1$01234567$b5lh2mHyD2PdJjFfALlEz1")

    def test_md5_crypt_unicode(self):
        """
        Tests the MD5 crypt function using some simple values
        encoded in unicode.
        """

        result = colony.md5_crypt(colony.legacy.u("password"), colony.legacy.u("salt"))
        self.assertEqual(type(result), colony.legacy.UNICODE)
        self.assertEqual(result, "$1$salt$qJH7.N4xYta3aEG/dfqo/0")

        result = colony.md5_crypt(
            colony.legacy.u("password"), colony.legacy.u("01234567")
        )
        self.assertEqual(type(result), colony.legacy.UNICODE)
        self.assertEqual(result, "$1$01234567$b5lh2mHyD2PdJjFfALlEz1")

        result = colony.md5_crypt(colony.legacy.u("密码"), colony.legacy.u("01234567"))
        self.assertEqual(type(result), colony.legacy.UNICODE)
        self.assertEqual(result, "$1$01234567$MUE6EDF7dbbvoFo3c.Oj1.")
